function normalizedCode(value) {
  return String(value || "").trim().toLocaleLowerCase().replaceAll("_", "-");
}

function resourceCandidates(record) {
  const available = new Set(record?.available || []);
  const recommendedFallback = new Set([
    "glottolog",
    "cldr",
    "kaikki",
    "ud",
    "udpipe",
    "unimorph",
    "panlex",
    "grambank",
    "phoible",
    "wikimedia-pronunciation",
    "forvo",
  ]);
  return languageDataSources
    .filter((source) => available.has(source.id) || recommendedFallback.has(source.id))
    .map((source) => ({
      id: source.id,
      name: source.name,
      category: source.category,
      version: source.version,
      url: source.url,
      license: source.license,
      automation: source.automation,
      access: source.access,
      status: available.has(source.id) ? "available" : "candidate",
      selected: available.has(source.id)
        ? source.defaultSelected
        : !record && ["glottolog", "cldr", "kaikki"].includes(source.id),
    }));
}

export function resolveLanguageInitialization(input = {}) {
  const requestedCode = normalizedCode(input.code);
  const requestedName = String(input.name || "").trim();
  const baseCode = requestedCode.split("-")[0];
  const nameKey = requestedName.toLocaleLowerCase();
  const record = languageCatalog.find((candidate) => (
    candidate.codes.includes(requestedCode)
    || candidate.codes.includes(baseCode)
    || [candidate.name, candidate.glottologName].some((name) => name.toLocaleLowerCase() === nameKey)
  ));
  const resolvedCode = requestedCode || record?.codes[0] || "";

  return {
    matched: Boolean(record),
    releaseDate: RESOURCE_RELEASE_DATE,
    name: record?.name || requestedName,
    code: resolvedCode,
    identity: {
      bcp47: resolvedCode,
      iso6393: record?.iso6393 || (baseCode.length === 3 ? baseCode : ""),
      glottocode: record?.glottocode || "",
      glottologName: record?.glottologName || "",
    },
    orthography: {
      script: record?.script || "",
      direction: record?.direction || "ltr",
      exemplars: record?.exemplars || "",
    },
    segmentation: {
      strategy: record?.strategy || "whitespace",
      source: record?.available?.includes("ud") ? "ud" : "cldr-heuristic",
    },
    sample: record?.sample || "",
    resources: resourceCandidates(record),
  };
}

export function dataSourceById(id) {
  return sourceMap.get(id) || null;
}

export function selectedResourceManifest(resources = []) {
  return resources
    .filter((resource) => resource.selected)
    .map((resource) => ({
      id: resource.id,
      version: resource.version,
      category: resource.category,
      status: resource.status,
      url: resource.url,
      license: resource.license,
    }));
}
